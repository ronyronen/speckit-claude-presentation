"""Generate the EN and HE decks from presentation/content/deck.yaml.

    python3 -m presentation.build.build_decks --lang en|he|both
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from pptx import Presentation

from .layouts import LAYOUTS, add_footer
from .model import load_deck, timing_prefixes
from .reader import reader_md
from .shapes import DIAGRAMS
from .text import _HE, set_rtl
from .theme import SLIDE_H, SLIDE_W
from .validate import validate

PRES = Path(__file__).resolve().parents[1]
DECK = PRES / "content" / "deck.yaml"
OUT = {"en": PRES / "speckit-workshop.pptx", "he": PRES / "speckit-workshop-he.pptx"}
TRANSCRIPT = {"en": PRES / "transcript-en.md", "he": PRES / "transcript-he.md"}
BLANK = 6


_LATIN = re.compile(r"[A-Za-z]")


def _he_leaves(node):
    """Every HE string inside a nested {en, he} structure, in order."""
    if isinstance(node, dict):
        if isinstance(node.get("he"), str):
            yield node["he"]
        for k, v in node.items():
            if k != "he":
                yield from _he_leaves(v)
    elif isinstance(node, list):
        for v in node:
            yield from _he_leaves(v)


def on_slide_he(s):
    """HE text lines shown on a slide (not notes): title, bullets, tip,
    layout extras (columns, tables, captions) and diagram labels."""
    texts = [s.title.get("he", "")] + [b.he for b in s.bullets]
    if s.tip:
        texts.append(s.tip.he)
    texts += list(_he_leaves(s.extra)) + list(_he_leaves(s.diagram))
    return [ln for t in texts for ln in t.splitlines()]


def list_mixed_lines(deck) -> list[tuple[str, str]]:
    """(slide id, line) for every on-slide HE line mixing Hebrew and Latin."""
    return [(s.id, ln) for s in deck.slides for ln in on_slide_he(s)
            if _HE.search(ln) and _LATIN.search(ln)]


CHECK_MD = Path(__file__).resolve().parent / "he_manual_check.md"


def manual_check_md(deck) -> str:
    """Checklist for the PowerPoint pass on the HE deck: per slide, every
    mixed Hebrew/English line and the tip."""
    mixed = list_mixed_lines(deck)
    out = ["# HE deck: manual bidi check (PowerPoint)", "",
           "Generated by `python3 -m presentation.build.build_decks --manual-check`.",
           "Open `presentation/speckit-workshop-he.pptx` in PowerPoint. For each line, check that",
           "English terms, numbers, `#N`, `°C`, slashes, quotes and brackets sit in the right",
           "place in the right-to-left sentence, and that nothing is clipped.", ""]
    for n, s in enumerate(deck.slides, 1):
        tip = s.tip.he if s.tip else None
        lines = [ln for sid, ln in mixed if sid == s.id and ln != tip]
        if not lines and not tip:
            continue
        out.append(f"## {n}. {s.id}")
        out += [f"- [ ] {ln}" for ln in lines]
        if tip:
            out.append(f"- [ ] TIP: {tip}")
        out.append("")
    return "\n".join(out)


def transcript_md(deck, lang) -> str:
    """The transcript as a reader's edition (see reader.py): no timings,
    no presenter cues, numbered references. HE is wrapped in an RTL div."""
    return reader_md(deck, lang, OUT[lang].name)


def new_presentation():
    prs = Presentation()
    prs.slide_width, prs.slide_height = SLIDE_W, SLIDE_H
    return prs


def _notes(slide, text, lang):
    tf = slide.notes_slide.notes_text_frame
    tf.text = text
    if lang == "he":
        for p in tf.paragraphs:
            set_rtl(p)


def build(deck_path: str, lang: str, out_path: str) -> None:
    deck = load_deck(deck_path)
    errs = validate(deck, set(DIAGRAMS))
    if errs:
        raise SystemExit("deck.yaml is invalid:\n" + "\n".join(errs))
    prefixes = timing_prefixes(deck)
    prs = new_presentation()
    label = deck.slides[0].title.get(lang, "") if deck.slides else ""
    for n, s in enumerate(deck.slides, 1):
        if s.layout not in LAYOUTS:
            raise SystemExit(f"{s.id}: unknown layout {s.layout!r}")
        slide = prs.slides.add_slide(prs.slide_layouts[BLANK])
        slide._element.cSld.set("name", s.id)
        LAYOUTS[s.layout](slide, s, lang, deck.glossary_keep_en)
        if s.layout != "title":
            add_footer(slide, n, label, lang, deck.glossary_keep_en)
        _notes(slide, prefixes[s.id] + "\n" + s.notes.get(lang, ""), lang)
    prs.save(out_path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lang", choices=["en", "he", "both"], default="both")
    ap.add_argument("--deck", default=str(DECK))
    ap.add_argument("--manual-check", action="store_true",
                    help=f"write {CHECK_MD.name} instead of building")
    args = ap.parse_args(argv)
    if args.manual_check:
        CHECK_MD.write_text(manual_check_md(load_deck(args.deck)), encoding="utf-8")
        print(f"wrote {CHECK_MD}")
        return 0
    for lang in (["en", "he"] if args.lang == "both" else [args.lang]):
        build(args.deck, lang, str(OUT[lang]))
        print(f"wrote {OUT[lang]}")
        TRANSCRIPT[lang].write_text(transcript_md(load_deck(args.deck), lang),
                                    encoding="utf-8")
        print(f"wrote {TRANSCRIPT[lang]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
